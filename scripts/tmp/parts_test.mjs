import fs from 'node:fs';
import { World } from '../../server/world.js';
import { capture } from '../../server/capture.js';
const lib = JSON.parse(fs.readFileSync('data/library/index.json', 'utf8'));
const cat = {};
for (const m of lib.models) cat[m.id] = { name: m.id, url: `/library/${m.file.split('/').map(encodeURIComponent).join('/')}`, pivot: m.pivot, nodes: m.nodes, scale: m.scale, localSize: m.localSize, size: m.localSize.map((v) => v * m.scale) };
const w = new World(cat);
w.place({ model: 'polyhaven/ArmChair_01', x: 5, z: 5, rotation: 0 });
w.place({ model: 'polyhaven/wooden_barrels_01#barrel01', x: 3, z: 5 });
w.place({ model: 'polyhaven/wooden_barrels_01#barrel02', x: 3.9, z: 5 });
w.place({ model: 'polyhaven/rock_moss_set_01#rock03', x: 7.5, z: 5 });
w.place({ model: 'lazytextures/Tree10', x: 5, z: 2 });
w.place({ model: 'polyhaven/metal_office_desk', x: 5, z: 7.5, rotation: 0 });
w.place({ model: 'polyhaven/pliers', x: 4.7, z: 7.5, on_top_of: '6' });
w.place({ model: 'polyhaven/metal_toolbox', x: 5.4, z: 7.5, on_top_of: '6' });
const imgs = await capture('http://127.0.0.1:5173', w.snapshot(), ['south', 'top']);
for (const im of imgs) fs.writeFileSync(`/private/tmp/claude-501/-Users-makosst-dev-worldmodel/f306e6f6-7dbb-4e44-8808-427f30fca738/scratchpad/shots/parts_${im.view}.jpg`, Buffer.from(im.data, 'base64'));
console.log(w.describe());
process.exit(0);
